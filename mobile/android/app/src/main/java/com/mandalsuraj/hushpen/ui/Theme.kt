/** The page behind grouped lists and the fill of their rows, which differ by appearance. */
@Immutable
data class Surfaces(val page: Color, val item: Color)

val LocalSurfaces = staticCompositionLocalOf { Surfaces(Color.Unspecified, Color.Unspecified) }

@Composable
fun HushpenTheme(dark: Boolean = isSystemInDarkTheme(), content: @Composable () -> Unit) {
    val context = LocalContext.current
    val scheme = when {
        Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> if (dark) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        dark -> FallbackDark
        else -> FallbackLight
    }
    val surfaces = if (dark) {
        Surfaces(page = scheme.surface, item = scheme.surfaceContainer)
    } else {
        Surfaces(page = scheme.surfaceContainerLow, item = scheme.surfaceContainerLowest)
    }
    CompositionLocalProvider(LocalSurfaces provides surfaces) {
        MaterialTheme(colorScheme = scheme, content = content)
    }
}

